#!/usr/bin/env python3
"""Regenerates src/theme/tokens.css: the Hokusai palette plus the seigaiha wave textures as data URIs."""
import urllib.parse

def wave(stroke, fa, fb, sw=1.2):
    def scale(x, y):
        out = f'<g transform="translate({x} {y})" stroke="{stroke}" stroke-width="{sw}">'
        for r, f in ((30, fa), (24, fb), (18, fa), (12, fb), (6, fa)):
            out += f'<circle r="{r}" fill="{f}"/>'
        return out + '</g>'
    body = ''.join(scale(x, y) for x, y in ((30, -15), (0, 0), (60, 0), (30, 15), (0, 30), (60, 30), (30, 45)))
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="60" height="30" viewBox="0 0 60 30">{body}</svg>'
    return 'url("data:image/svg+xml,' + urllib.parse.quote(svg, safe="") + '")'

css = f"""/*
 * Hokusai documentation palette, taken from the Hokusai logo: the pale sky of its panel, the black and
 * white of the swallows, and the vermillion of their throats. The sea texture is seigaiha, the traditional
 * Japanese wave pattern. Generated by scripts/gen-theme-tokens.py; these tokens are owned by this repository.
 */
:root {{
  --hk-bg: #0a1822;
  --hk-surface: #102431;
  --hk-surface-2: #14303f;
  --hk-text: #eaf4fb;
  --hk-muted: #9bb4c4;
  --hk-faint: #6d8798;
  --hk-border: #214052;
  --hk-sky: #a8e1fb;
  --hk-sky-deep: #7fd0f5;
  --hk-link: #8bd5f7;
  --hk-vermillion: #ee5a43;
  --hk-on-vermillion: #ffffff;
  --hk-code-bg: #081420;
  --hk-ink: #0a0a0a;
  --hk-wave: {wave("#235a77", "#0e2230", "#0b1b27")};
  --hk-wave-panel: {wave("#6fbfe4", "#b9e8fd", "#a8e1fb", 1.3)};
}}

:root[data-theme='light'] {{
  --hk-bg: #fbfaf6;
  --hk-surface: #ffffff;
  --hk-surface-2: #eef7fc;
  --hk-text: #12181f;
  --hk-muted: #475763;
  --hk-faint: #75858f;
  --hk-border: #d3e3ec;
  --hk-sky-deep: #2b7aa8;
  --hk-link: #1d5a85;
  --hk-vermillion: #c8321f;
  --hk-code-bg: #f3f8fb;
  --hk-wave: {wave("#cde6f3", "#f7fcff", "#eef8fe")};
}}
"""
open("src/theme/tokens.css", "w").write(css)
